#!/usr/bin/env python3
"""Generate completions/gozar.fish from argparse — never from memory.

The completion file used to be hand-maintained, so it drifted: `engine`,
`selfcheck` and a dozen newer flags were missing, and deleting them from the
file was the only way anyone noticed. This script asks the parser itself.

    python3 scripts/gen-completions.py          # rewrite the file
    python3 scripts/gen-completions.py --check   # exit 1 if it is out of date
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "completions" / "gozar.fish"


def _desc(action) -> str:
    return (action.help or "").strip().replace('"', "'").replace("--", "")


def _takes_value(action) -> bool:
    if isinstance(action, (argparse._StoreTrueAction, argparse._StoreFalseAction,
                           argparse._CountAction, argparse._HelpAction,
                           argparse._StoreConstAction)):
        return False
    return action.nargs != 0


def build() -> str:
    sys.path.insert(0, str(ROOT))
    from gozar.cli import build_parser

    p = build_parser()
    sub = next(a for a in p._actions if isinstance(a, argparse._SubParsersAction))
    choices = list(sub.choices)
    # argparse records each subcommand's help text here, in order
    helps = {a.dest: a.help for a in sub._choices_actions}

    out = [
        "# fish completion for `gozar` — GENERATED from argparse (gozar/cli.py).",
        "# Do not edit by hand: python3 scripts/gen-completions.py rewrites it,",
        "# and tests/test_contracts.py fails when it is out of date.",
        "",
        "set -l gozar_cmds " + " ".join(choices),
        "complete -c gozar -f",
        "",
        "# subcommands",
    ]
    for name in choices:
        d = (helps.get(name) or "").replace('"', "'").replace("--", "")
        out.append('complete -c gozar -n "not __fish_seen_subcommand_from '
                   f'$gozar_cmds" -a {name} -d "{d}"')

    def flag_lines(sp, cond: str) -> list[str]:
        lines = []
        # positional arguments with a fixed set of choices (engine status|install)
        for a in sp._actions:
            if a.option_strings or isinstance(a, argparse._HelpAction):
                continue
            ch = getattr(a, "choices", None)
            if ch:
                lines.append(f'complete -c gozar -n "{cond}" -a "'
                             + " ".join(ch) + f'" -d "{_desc(a)}"')
        for a in sp._actions:
            if a.dest == "help" or isinstance(a, argparse._HelpAction):
                continue
            longs = [o for o in a.option_strings if o.startswith("--")]
            if not longs:
                continue
            shorts = [o for o in a.option_strings if len(o) == 2]
            bits = [f'complete -c gozar -n "{cond}"']
            if shorts:
                bits.append(f"-s {shorts[0][1:]}")
            bits.append(f"-l {longs[0][2:]}")
            if _takes_value(a):
                bits.append("-r")
                ch = getattr(a, "choices", None)
                if ch:
                    bits.append('-a "' + " ".join(ch) + '"')
                elif a.dest in ("config", "data_dir", "engine_dir", "import",
                                "config_out"):
                    bits.append("-F")
            d = _desc(a)
            if d:
                bits.append(f'-d "{d}"')
            lines.append(" ".join(bits))
        return lines

    for name in choices:
        out.append("")
        out.append(f"# {name}")
        out.extend(flag_lines(sub.choices[name],
                              f"__fish_seen_subcommand_from {name}"))

    out.append("")
    out.append("# flags accepted before the subcommand")
    top = argparse.ArgumentParser(add_help=False)
    for a in p._actions:
        if a.dest in ("help", "cmd") or isinstance(a, argparse._HelpAction):
            continue
        top._actions.append(a)
    out.extend(flag_lines(top, "not __fish_seen_subcommand_from $gozar_cmds"))

    return "\n".join(out) + "\n"


def _collect():
    """(top-level flags, {cmd: (help, [actions])}) straight from argparse."""
    sys.path.insert(0, str(ROOT))
    from gozar.cli import build_parser
    p = build_parser()
    sub = next(a for a in p._actions if isinstance(a, argparse._SubParsersAction))
    helps = {a.dest: a.help for a in sub._choices_actions}
    top = [a for a in p._actions
           if a.dest not in ("help", "cmd") and not isinstance(a, argparse._HelpAction)]
    return top, sub.choices, helps


def build_bash() -> str:
    """bash completion: same data, one function, no external tools."""
    top, choices, helps = _collect()
    out = ["# bash completion for gozar — GENERATED by scripts/gen-completions.py",
           "# install: source this file, or drop it in /etc/bash_completion.d/",
           "_gozar() {",
           "    local cur prev cmd",
           '    COMPREPLY=()',
           '    cur="${COMP_WORDS[COMP_CWORD]}"',
           '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
           "    local cmds=\"" + " ".join(choices) + "\"",
           '',
           '    if [ "$COMP_CWORD" -eq 1 ]; then',
           '        COMPREPLY=( $(compgen -W "$cmds" -- "$cur") )',
           "        return 0",
           "    fi",
           '    cmd="${COMP_WORDS[1]}"',
           '    case "$cmd" in']
    for name, sp in choices.items():
        flags = sorted({o for a in sp._actions for o in a.option_strings
                        if o.startswith("--")})
        words = " ".join(flags)
        out.append(f"        {name})")
        out.append(f'            COMPREPLY=( $(compgen -W "{words}" -- "$cur") ) ;;')
    out += ["        *)",
            '            COMPREPLY=( $(compgen -W "$cmds" -- "$cur") ) ;;',
            "    esac",
            "    return 0",
            "}",
            "complete -F _gozar gozar"]
    return "\n".join(out) + "\n"


def build_zsh() -> str:
    """zsh completion using _arguments (native, no bashcompinit)."""
    top, choices, helps = _collect()
    out = ["#compdef gozar",
           "# zsh completion for gozar — GENERATED by scripts/gen-completions.py",
           "# install: drop in a dir on $fpath as _gozar, then `compinit`",
           "",
           "_gozar() {",
           "  local -a cmds",
           "  cmds=("]
    for name in choices:
        d = (helps.get(name) or "").replace('"', "'").replace("--", "").replace("'", "\'")
        out.append(f"    '{name}:{d}'")
    out += ["  )", "",
            "  _arguments -C \\",
            "    '(-h --help)'{-h,--help}'[show help]' \\",
            "    '--version[show version]' \\",
            "    '-c[config file]:file:_files' \\",
            "    '-v[verbose]' '-q[quiet]' \\",
            "    '--hard[filtered-line preset]' \\",
            "    '--reset[start a fresh pool]' \\",
            "    '1:command:->cmds' \\",
            "    '*::arg:->args'", "",
            "  case $state in",
            "    cmds) _describe 'command' cmds ;;",
            "    args)",
            "      case $words[1] in"]
    for name, sp in choices.items():
        flags = sorted({o for a in sp._actions for o in a.option_strings
                        if o.startswith("--")})
        out.append(f"        {name})")
        specs = []
        for f in flags:
            act = next(a for a in sp._actions if f in a.option_strings)
            # zsh single-quoted specs cannot contain an apostrophe
            d = _desc(act).replace("'", "")
            specs.append(f"'{f}[{d}]'")
        out.append("          _arguments " + " \\\n            ".join(specs) + " ;;")
    out += ["      esac ;;", "  esac", "}", "", '_gozar "$@"']
    return "\n".join(out) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("completions/gozar.fish is OUT OF DATE — run "
                  "python3 scripts/gen-completions.py")
            return 1
        print("completions are in sync with argparse")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    for fn, name in ((build_bash, "gozar.bash"), (build_zsh, "_gozar")):
        target = OUT.parent / name
        body = fn()
        target.write_text(body)
        print(f"wrote {target.relative_to(ROOT)} ({len(body.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
